import { Keypair } from "@solana/web3.js";
import { ed25519 } from "@noble/curves/ed25519";
import { createClient } from "@supabase/supabase-js";
import { buildWalletSignInMessage } from "./src/lib/identity/wallet-message";
import fs from "node:fs";
const B = "http://localhost:8080";
const kp = Keypair.fromSecretKey(Uint8Array.from(JSON.parse(fs.readFileSync("/tmp/e2e/wallet.json","utf8"))));
const address = kp.publicKey.toBase58();
const message = buildWalletSignInMessage({ host: "localhost:8080", origin: B, address, issuedAt: new Date().toISOString() });
const signature = Buffer.from(ed25519.sign(new TextEncoder().encode(message), kp.secretKey.slice(0,32))).toString("base64");
const si = await (await fetch(`${B}/api/wallet/sign-in`, { method: "POST", headers: { "Content-Type": "application/json", Origin: B }, body: JSON.stringify({ message, signature }) })).json();
const sb = createClient(process.env.VITE_SUPABASE_URL!, process.env.VITE_SUPABASE_PUBLISHABLE_KEY!, { auth: { persistSession: false } });
const { data: sess } = await sb.auth.verifyOtp({ token_hash: si.tokenHash, type: "magiclink" });
fs.writeFileSync("/tmp/e2e/token.txt", sess.session!.access_token);
const H = { Authorization: `Bearer ${sess.session!.access_token}`, "Content-Type": "application/json" };
const [m, p, b] = process.argv.slice(2);
const x = await fetch(B + p, { method: m, headers: H, body: b });
console.log(m, p, x.status, (await x.text()).slice(0, 1500));
