import { Keypair } from "@solana/web3.js";
import nacl from "tweetnacl";
import { createClient } from "@supabase/supabase-js";
import { buildWalletSignInMessage } from "./src/lib/identity/wallet-message";
import fs from "node:fs";
const B = "http://localhost:8080";
const kpFile = "/tmp/e2e/wallet.json";
const kp = fs.existsSync(kpFile) ? Keypair.fromSecretKey(Uint8Array.from(JSON.parse(fs.readFileSync(kpFile,"utf8")))) : Keypair.generate();
fs.writeFileSync(kpFile, JSON.stringify([...kp.secretKey]));
const address = kp.publicKey.toBase58();
const log = (k: string, v: unknown) => console.log(`## ${k}:`, JSON.stringify(v).slice(0, 700));
log("wallet", address);
const message = buildWalletSignInMessage({ host: "localhost:8080", origin: B, address, issuedAt: new Date().toISOString() });
const signature = Buffer.from(nacl.sign.detached(new TextEncoder().encode(message), kp.secretKey)).toString("base64");
let r = await fetch(`${B}/api/wallet/sign-in`, { method: "POST", headers: { "Content-Type": "application/json", Origin: B }, body: JSON.stringify({ message, signature }) });
const si = await r.json(); log("sign-in " + r.status, { address: si.address, gotToken: !!si.tokenHash });
r = await fetch(`${B}/api/wallet/sign-in`, { method: "POST", headers: { "Content-Type": "application/json", Origin: B }, body: JSON.stringify({ message, signature }) });
log("replay " + r.status, await r.json());
const sb = createClient(process.env.VITE_SUPABASE_URL!, process.env.VITE_SUPABASE_PUBLISHABLE_KEY!, { auth: { persistSession: false } });
const { data: sess, error } = await sb.auth.verifyOtp({ token_hash: si.tokenHash, type: "magiclink" });
if (error) throw error;
const H = { Authorization: `Bearer ${sess.session!.access_token}`, "Content-Type": "application/json" };
fs.writeFileSync("/tmp/e2e/user.txt", sess.user!.id);
const call = async (m: string, p: string, body?: unknown) => { const x = await fetch(B + p, { method: m, headers: H, body: body ? JSON.stringify(body) : undefined }); const j = await x.json().catch(() => null); log(`${m} ${p} ${x.status}`, j); return j; };
await call("GET", "/api/kyc");
const pay = await call("POST", "/api/payments", { amount: "25", wallet: address, country: "GB", currency: "GBP" });
const id = pay?.payment?.id ?? pay?.id;
if (!id) process.exit(0);
fs.writeFileSync("/tmp/e2e/payment.txt", id);
await call("POST", `/api/payments/${id}/quote`);
await call("POST", `/api/payments/${id}/payout-details`, { holderName: "Test Sandbox", beneficiary: { bankName: "Barclays", accountNumber: "31926819", address: { street: "1 High St", city: "London", state: "London", postalCode: "EC1A1BB", country: "GB" }, details: { sort_code: "601613" } } });
await call("GET", `/api/payments/${id}`);
